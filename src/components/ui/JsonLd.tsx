/**
 * Renders one or more schema.org objects as JSON-LD in the server HTML, where
 * crawlers that do not execute JavaScript can still read them.
 */
export default function JsonLd({ data }: { data: object | object[] }) {
  const items = Array.isArray(data) ? data : [data];
  return (
    <>
      {items.map((item, i) => (
        <script
          key={i}
          type="application/ld+json"
          // JSON.stringify output cannot contain a closing script tag once "<" is escaped.
          dangerouslySetInnerHTML={{ __html: JSON.stringify(item).replace(/</g, "\\u003c") }}
        />
      ))}
    </>
  );
}
